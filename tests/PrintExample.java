// Expected output: Total: 5, 5, 5 items, Digits: 23, Sum: 5, Label: 5
// (Each item is on a separate line.)
public class PrintExample {
    public static void main(String[] args) {
        int total = 5;
        String label = "Label: ";
        System.out.println("Total: " + total);
        System.out.println(2 + 3);
        System.out.println(2 + 3 + " items");
        System.out.println("Digits: " + 2 + 3);
        System.out.println("Sum: " + (2 + 3));
        System.out.print(label + total);
        System.out.println();
    }
}
